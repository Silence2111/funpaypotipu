// i18n-ignore-start

/** 0.044 → «4,4%», 0.1 → «10%». */
const pct = (v: number) => `${new Intl.NumberFormat('ru-RU', { maximumFractionDigits: 1 }).format(v * 100)}%`;
/** 150 bps → «1,5 п.п.» */
const pp = (bps: number) => `${new Intl.NumberFormat('ru-RU', { maximumFractionDigits: 1 }).format(bps / 100)} п.п.`;
const rating = (v: number) => new Intl.NumberFormat('ru-RU', { minimumFractionDigits: 1 }).format(v);
/** «4 ч», «1 ч» — сроки в часах. */
const hours = (h: number) => `${h} ч`;
const days = (d: number) => `${d} ${d === 1 ? 'день' : d < 5 ? 'дня' : 'дней'}`;
const fee = (m: (typeof WITHDRAWAL_METHODS)[number]) =>
  m.minFee > 0n ? `${pct(m.feePct)}, не меньше ${formatPrice(m.minFee.toString())}` : pct(m.feePct);

/** Способ оплаты внутри фразы: «карта», а не «Банковская карта». */
const METHOD_WORDS: Record<string, string> = {
  balance: 'баланс',
  sbp: 'СБП',
  crypto: 'криптовалюта',
  card: 'карта',
};
/** «а, б и в». */
const listRu = (words: string[]) =>
  words.length > 1 ? `${words.slice(0, -1).join(', ')} и ${words[words.length - 1]}` : (words[0] ?? '');
const cap = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);

/** Способы с надбавкой или без — только те, что принимает шлюз: у ЮKassa нет криптовалюты. */
const methodsWhere = (paidOnly: boolean, c: Terms) =>
  listRu(
    PAYMENT_METHODS.filter(
      (m) => (m.feePct > 0) === paidOnly && (m.key === 'balance' || !c.payMethods || c.payMethods.includes(m.key)),
    ).map((m) => METHOD_WORDS[m.key] ?? m.label),
  );
const surcharge = pct(PAYMENT_METHODS.find((m) => m.feePct > 0)?.feePct ?? 0);
/** «7–10%» или «10%», если ставка одна. */
const feeRange = (t: Terms) =>
  t.feeMin === t.feeMax ? pct(t.feeMin) : `${pct(t.feeMin).replace('%', '')}–${pct(t.feeMax)}`;

/** Срок проверки у уровня продавца: не дольше общего срока площадки. */
const levelHours = (t: Terms, key: keyof typeof SELLER_LEVELS) =>
  hours(Math.min(SELLER_LEVELS[key].holdHours, t.confirmHours));

