/**
 * Условия площадки для статей «Помощи». Цифры — из `GET /fees/public` и
 * общего пакета, по которым считаются сделки: поменяли комиссию или срок —
 * статья говорит новое, а не то, что было при её написании. Запасные
 * значения нужны, только если API не ответил.
 */
export interface Terms {
  feeMin: number;
  feeMax: number;
  cashback: number;
  confirmHours: number;
  fulfillHours: number;
  autoGoodsHours: number;
  promoDay: string;
  kycAbove: string;
  newbieHoldDays: number;
  demo: boolean;
  /** Способы, которые принимает платёжный шлюз; null — все. */
  payMethods: string[] | null;
}

export function termsFrom(p: PublicPricing | null): Terms {
  return {
    feeMin: p?.sellerFeeMinPct ?? 0.07,
    feeMax: p?.sellerFeeMaxPct ?? 0.1,
    cashback: p?.cashbackPct ?? 0.02,
    confirmHours: p?.autoConfirmHours ?? 72,
    fulfillHours: p?.fulfillHours ?? 24,
    autoGoodsHours: p?.autoGoodsConfirmHours ?? 24,
    promoDay: p?.promoDayPrice ?? '9900',
    kycAbove: p?.payoutKycAboveMinor ?? '1500000',
    newbieHoldDays: p?.payoutNewbieHoldDays ?? 3,
    demo: p?.paymentsDemo ?? false,
    payMethods: p?.payMethods ?? null,
  };
}

