/**
 * Плитка для карточки без обложки.
 *
 * Пока продавцы не загрузили картинки, каталог был стеной одинаковых серых
 * прямоугольников с иконкой «нет изображения». Для маркетплейса игровых
 * товаров это читается как сломанная страница: у конкурентов первый экран
 * держится именно на обложках.
 *
 * Чужие обложки игр брать нельзя — это чужая интеллектуальная собственность.
 * Поэтому плитка рисуется своя: цвет выводится из названия, поэтому у одной
 * игры он всегда один и тот же, и каталог перестаёт быть серым, ничего при
 * этом не выдавая за настоящую картинку.
 */

/** Устойчивый хеш строки. Одинаковое название — одинаковый цвет, всегда. */
function hash(input: string): number {
  let h = 2166136261;
  for (let i = 0; i < input.length; i += 1) {
    h ^= input.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return Math.abs(h);
}

export interface Tile {
  /** Фон плитки. */
  background: string;
  /** Цвет буквы. */
  color: string;
  /** Что показать: одна-две буквы названия. */
  initials: string;
}

export function tileFor(title: string): Tile {
  const h = hash(title || '?');
  // Тон свободный, насыщенность и светлота зажаты: пёстрой мозаики не выйдет,
  // а плитки останутся различимыми и в светлой, и в тёмной теме.
  // Золотой угол разносит соседние хеши по кругу: без него половина каталога
  // оказывается в одном зелёном секторе, как вышло на первой сборке.
  const hue = (h * 137) % 360;
  const sat = 52 + (h % 3) * 7; // 52/59/66 — чуть разной насыщенности
  const light = 42 + ((h >> 3) % 3) * 5; // 42/47/52 — соседи одного тона различимы
  const background = `hsl(${hue} ${sat}% ${light}%)`;
  const initials = title
    .split(/\s+/)
    .filter(Boolean)
    .slice(0, 2)
    .map((w) => w[0])
    .join('')
    .toUpperCase()
    .slice(0, 2);
  return { background, color: 'rgba(255,255,255,0.92)', initials: initials || '?' };
}
