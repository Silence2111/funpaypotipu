import type { Metadata } from 'next';
import { LegalPage, Fill } from '@/components/legal-page';
import { getPublicPricing } from '@/lib/api';

export const metadata: Metadata = { title: 'Оферта' };

export default async function OfertaPage() {
  const p = await getPublicPricing();
  const pct = (v: number) => `${String(+(v * 100).toFixed(1)).replace('.', ',')}%`;
  return (
    <LegalPage title="Оферта">
      <p>Оператор площадки: <Fill what="наименование, ИНН, ОГРН, адрес" />. Далее — «площадка».</p>
      <h2>1. Что делает площадка</h2>
      <p>
        Сводит покупателей и продавцов цифровых игровых товаров, принимает оплату, хранит её до
        подтверждения получения и проводит выплату продавцу. Площадка не является продавцом товара.
      </p>
      <h2>2. Сколько это стоит</h2>
      <ul>
        <li>Покупатель комиссию площадки не платит.</li>
        {p && p.sellerFeeMinPct > 0 && (
          <li>
            Продавец платит {pct(p.sellerFeeMinPct)}–{pct(p.sellerFeeMaxPct)} от цены в зависимости от категории;
            ставка снижается с уровнем продавца до {p.levelDiscountMaxPp} п.п.
          </li>
        )}
        {p && <li>Вывод денег: {p.withdrawal.map((w) => `${w.label} — ${pct(w.feePct)}`).join(', ')}.</li>}
      </ul>
      <h2>3. Гарантия сделки</h2>
      <ol>
        <li>Оплата удерживается площадкой и не передаётся продавцу до подтверждения получения.</li>
        <li>
          Продавец выдаёт товар в течение {p?.fulfillHours ?? 24} ч, иначе заказ отменяется и деньги возвращаются
          на баланс покупателя.
        </li>
        <li>
          После выдачи у покупателя {p?.autoConfirmHours ?? 72} ч на проверку. Без подтверждения и без спора заказ
          подтверждается автоматически.
        </li>
        <li>Спор рассматривает арбитр площадки по переписке и приложенным материалам.</li>
      </ol>
      <h2>4. Возврат</h2>
      <p>
        Возврат зачисляется на баланс площадки. Вывод с баланса на карту: <Fill what="порядок после подключения платёжного провайдера" />.
      </p>
      <h2>5. Запрещено</h2>
      <p>Товары, нарушающие правила игр и законы РФ, обмен контактами в обход площадки, фиктивные сделки.</p>
    </LegalPage>
  );
}
