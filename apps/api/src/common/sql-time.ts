import { Prisma } from '@gamemarket/db';

/**
 * Момент времени для сырого SQL: `${utc(date)}` вместо `${date}`.
 *
 * Время в базе — `timestamp(3)` в UTC без пояса, а дату из JS Prisma в
 * сыром запросе передаёт как `timestamptz`. Сравнивая и записывая, база
 * переводит её в пояс соединения — и при поясе не UTC (управляемый Postgres
 * с московским поясом, встроенный Postgres на маке) время уезжало на 3
 * часа: скидки кончались раньше срока, «в сети» не было никого, сводка по
 * дням не сходилась с итогом, `updated_at` писался московским. Приведение
 * `::timestamp` не спасает — оно тоже по поясу соединения. `AT TIME ZONE
 * 'UTC'` от пояса не зависит. Запросы Prisma без сырого SQL этим не болеют.
 */
export const utc = (d: Date): Prisma.Sql => Prisma.sql`(${d}::timestamptz AT TIME ZONE 'UTC')`;
