export const RULE_CLAUSES: RuleClause[] = RULE_GROUPS.flatMap((g) => g.clauses);
export const RULE_IDS = RULE_CLAUSES.map((c) => c.id);

export function ruleClause(id: string | null | undefined): RuleClause | null {
  return RULE_CLAUSES.find((c) => c.id === id) ?? null;
}

/** Якорь пункта на странице правил: «1.2» → «p-1-2». */
export const ruleAnchor = (id: string) => `p-${id.replace('.', '-')}`;

/** «п. 1.2 — Фиктивные сделки…» — в уведомлениях и консоли. */
export function ruleText(id: string | null | undefined): string | null {
  const c = ruleClause(id);
  return c ? `п. ${c.id} — ${c.title}` : null;
}

