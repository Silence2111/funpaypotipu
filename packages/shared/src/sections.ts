/** Слова «аккаунт» и «учётная запись» в разных формах. */
const ACC = '(?:аккаунт|акк(?![а-я])|учетк|учетн[а-я]*\\s+запис)';
const MINE = '(?:(?:свой|мой|этот|игровой|основной|личный|полный|свои|мои)\\s+)?';

const PATTERNS: RegExp[] = [
  // «логин и пароль», «логин/пароль», «логин + пароль»
  /логин\s*(?:и|\/|\+|,|:|&)?\s*парол/,
  /\blog(?:in)?\s*(?:and|\/|\+|:|&)\s*pass(?:word)?\b/,
  // «данные от аккаунта», «данные для входа»
  new RegExp(`данн[а-я]*\\s+(?:от|для|к)\\s+(?:вашего\\s+|своего\\s+|моего\\s+)?(?:${ACC}|вход)`),
  // «продам аккаунт», «передам свой аккаунт», «отдам акк»
  new RegExp(`(?:прода|переда|отда)[а-я]*\\s+${MINE}${ACC}`),
  // «продажа аккаунта», «передача учётной записи», «аренда аккаунта»
  new RegExp(`(?:продаж|передач|аренд)[а-я]*\\s+${MINE}${ACC}`),
  // «зайду на ваш аккаунт», «играю с вашего аккаунта» — буст под видом услуги
  new RegExp(
    `(?:зайду|захожу|войду|вхожу|зайти|войти|вход|играю|сыграю|поиграю|прокачаю|качаю|фармлю|апну)\\s+(?:на|в|с|через)\\s+(?:ваш|твой)[а-я]*\\s+${ACC}`,
  ),
  // «доступ к аккаунту», «доступ к вашему аккаунту»
  new RegExp(`доступ[а-я]*\\s+(?:к|от|в)\\s+(?:вашему\\s+|вашем\\s+|своему\\s+|моему\\s+)?${ACC}`),
  // «смена почты», «родная почта», «перепривязка» — признаки продажи аккаунта
  /(?:смен[а-я]*|родн[а-я]*)\s+(?:почт|e-?mail|мейл|майл|номер)/,
  /перепривяз/,
  // «общий доступ», «офлайн-аккаунт» — один аккаунт на нескольких покупателей
  /общ[а-я]+\s+доступ/,
  new RegExp(`(?:офф?лайн|offline)[\\s-]*(?:${ACC}|актива|account)`),
  // English
  /\b(?:sell|selling|transfer|transferring)\s+(?:my\s+|the\s+|this\s+)?account/,
  /\baccount\s+(?:access|sharing|transfer|login)\b/,
];

/** Латиница, похожая на кириллицу: «aккаунт» с латинской «a» — тоже аккаунт. */
const LOOKALIKE: Record<string, string> = { a: 'а', c: 'с', e: 'е', o: 'о', p: 'р', x: 'х', k: 'к', y: 'у', m: 'м', t: 'т', h: 'н', b: 'в' };

function normalize(text: string): string {
  return text
    .toLowerCase()
    .replace(/ё/g, 'е')
    .split(/(\s+)/)
    .map((w) => (/[а-я]/.test(w) && /[a-z]/.test(w) ? w.replace(/[a-z]/g, (ch) => LOOKALIKE[ch] ?? ch) : w))
    .join('')
    .replace(/\s+/g, ' ');
}

/**
 * Фраза о передаче аккаунта в тексте лота или null. Находка отправляет лот
 * на проверку модератору: он не выходит в каталог, пока его не одобрят.
 * Ключ «активируется на ваш аккаунт» и донат «на ваш аккаунт по ID» —
 * не находка: там аккаунт покупателя не покидает.
 */
export function accountTransferMatch(...parts: Array<string | null | undefined>): string | null {
  const text = normalize(parts.filter(Boolean).join(' \n '));
  for (const re of PATTERNS) {
    const m = re.exec(text);
    if (!m) continue;
    // До конца слова: модератор видит «логин и пароль», а не основу «парол».
    let end = m.index + m[0].length;
    while (end < text.length && /[а-яa-z]/.test(text[end]!)) end++;
    return text.slice(m.index, end).trim().slice(0, 60);
  }
  return null;
}

/** Строки из характеристик лота — для проверки вместе с названием и описанием. */
export function attributeText(attributes: unknown): string {
  if (!attributes || typeof attributes !== 'object') return '';
  return Object.values(attributes as Record<string, unknown>)
    .filter((v): v is string => typeof v === 'string')
    .join(' ');
}
